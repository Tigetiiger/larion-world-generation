package dev.tigetiiger.larionrim.compat;

import java.util.List;
import java.util.Set;
import net.fabricmc.loader.api.FabricLoader;
import org.objectweb.asm.tree.ClassNode;
import org.spongepowered.asm.mixin.extensibility.IMixinConfigPlugin;
import org.spongepowered.asm.mixin.extensibility.IMixinInfo;

/** Applies the SeedGen compat mixins only when Distant Horizons SeedGen is installed. */
public final class SeedGenMixinPlugin implements IMixinConfigPlugin {
    private static final boolean PRESENT = FabricLoader.getInstance().isModLoaded("seedrenderer")
            && !Boolean.getBoolean("larionrim.noSeedgenCompat"); // switch for A/B tests

    @Override public void onLoad(String mixinPackage) {}
    @Override public String getRefMapperConfig() { return null; }
    @Override public boolean shouldApplyMixin(String targetClassName, String mixinClassName) { return PRESENT; }
    @Override public void acceptTargets(Set<String> myTargets, Set<String> otherTargets) {}
    @Override public List<String> getMixins() { return null; }
    @Override public void preApply(String t, ClassNode c, String m, IMixinInfo i) {}
    @Override public void postApply(String t, ClassNode c, String m, IMixinInfo i) {}
}
